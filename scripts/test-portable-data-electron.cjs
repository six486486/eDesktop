const {app,BrowserWindow,session}=require('electron')
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const {initializePortableData}=require('../electron/portable-data.cjs')
const root=path.resolve('.artifacts/portable-data-electron',`run-${Date.now()}`),software=path.join(root,'software'),legacyBase=path.join(root,'old-appdata'),legacy=path.join(legacyBase,'eDesktop')
fs.mkdirSync(legacy,{recursive:true})
fs.writeFileSync(path.join(legacy,'desktop-workspace.json'),JSON.stringify({widgets:[{kind:'todo',data:{items:[{text:'保留原待办'}]}}]}))
fs.mkdirSync(path.join(legacy,'desktop-pet/speech/sensevoice'),{recursive:true})
fs.writeFileSync(path.join(legacy,'desktop-pet/speech/sensevoice/test-model.bin'),'model fixture')
app.setPath('appData',legacyBase)
assert.equal(initializePortableData(app,{projectRoot:software}),true)
const data=path.join(software,'data')
assert.equal(fs.existsSync(legacy),false)
fs.writeFileSync(path.join(software,'test.html'),'<!doctype html><title>portable data test</title><p>本地缓存验证</p>')
let window
app.whenReady().then(async()=>{
  for(const name of ['userData','sessionData'])assert.equal(app.getPath(name),data)
  assert.equal(session.defaultSession.storagePath,data)
  window=new BrowserWindow({show:false,webPreferences:{sandbox:true}})
  await window.loadFile(path.join(software,'test.html'))
  await window.webContents.executeJavaScript(`localStorage.setItem('portable-test','cached on D');localStorage.getItem('portable-test')`)
  session.defaultSession.flushStorageData()
  assert.ok(fs.existsSync(path.join(data,'Local Storage')))
  assert.equal(fs.existsSync(legacy),false,'Electron must not recreate the old roaming profile')
  assert.equal(JSON.parse(fs.readFileSync(path.join(data,'desktop-workspace.json'),'utf8')).widgets[0].data.items[0].text,'保留原待办')
  assert.equal(fs.readFileSync(path.join(data,'desktop-pet/speech/sensevoice/test-model.bin'),'utf8'),'model fixture')
  fs.writeFileSync(path.join(root,'result.json'),JSON.stringify({passed:true,data,legacyRemoved:!fs.existsSync(legacy),storagePath:session.defaultSession.storagePath},null,2))
  console.log('PASS Electron migration, portable session/cache and preserved workspace/model: '+root)
}).catch(error=>{console.error(error);process.exitCode=1}).finally(()=>{window?.destroy();app.exit(process.exitCode||0)})
